"""Error taxonomy and severity scale (DECISIONS.md ADR-009).

Design: the *closed* part (category, subcategory) is fixed enums so counts
aggregate reliably across sessions and across detectors — free-text labels
don't aggregate. The *open* part is the feature_key
(``category:subcategory:feature``), which captures the specific recurring
phenomenon and links error events into patterns for recurrence counting:

    morphosyntax:agreement:gender_noun_adj      (Spanish "el problema grande y *seria*")
    morphosyntax:case:dative_after_mit          (German "mit *der* Kind")
    morphosyntax:case:ergative_transitive       (Basque dropped -k on transitive subject)
    lexis:false_friend:actualmente              (used as "actually")
    pragmatics:register:tu_vs_usted             (informal address in formal context)

The feature portion is generated by the detector under instructions embedded in
the tool schema (tutor/schema.py): lowercase snake_case, reuse an existing key
when one fits (the prompt lists the profile's active keys), lemma for lexical
items. Fuzzy merging of near-duplicate keys is a Phase 1 concern.

These enum values are enforced in Python, not in SQL CHECKs, so extending the
taxonomy is a code change + backfill decision, not a migration (ADR-006).
"""

from __future__ import annotations

from enum import IntEnum, StrEnum


class ErrorCategory(StrEnum):
    MORPHOSYNTAX = "morphosyntax"
    LEXIS = "lexis"
    PRAGMATICS = "pragmatics"
    ORTHOGRAPHY = "orthography"
    PHONOLOGY = "phonology"
    COMPREHENSION = "comprehension"


class ErrorSubcategory(StrEnum):
    # morphosyntax
    AGREEMENT = "agreement"              # gender/number/person concord
    TENSE_ASPECT = "tense_aspect"        # wrong tense or aspect choice
    MOOD = "mood"                        # indicative/subjunctive/conditional choice
    CASE = "case"                        # case marking (German; Basque incl. ergative)
    WORD_ORDER = "word_order"            # constituent order, V2, clitic placement site
    DETERMINER = "determiner"            # article use/omission/choice
    PREPOSITION = "preposition"          # wrong/missing preposition
    PRONOUN = "pronoun"                  # pronoun/clitic form or omission
    NEGATION = "negation"                # negation structure (ne...pas, nicht placement)
    CONJUGATION = "conjugation"          # right tense, wrong form (stem/ending error)
    # lexis
    LEXICAL_CHOICE = "lexical_choice"    # wrong word for the meaning
    FALSE_FRIEND = "false_friend"        # L1/L3 lookalike with different meaning
    COLLOCATION = "collocation"          # words don't co-occur ("hacer una decisión")
    WORD_FORMATION = "word_formation"    # derivation/compounding error, invented word
    CALQUE = "calque"                    # literal translation of an L1/L3 structure
    MISSING_WORD = "missing_word"        # required lexical item omitted
    # pragmatics
    REGISTER = "register"                # formality level (tu/usted, du/Sie)
    IDIOMATICITY = "idiomaticity"        # grammatical but no native speaker says it
    DISCOURSE = "discourse"              # connectives, cohesion, topic management
    # orthography
    SPELLING = "spelling"
    DIACRITICS = "diacritics"            # accents, umlauts, hamza/madda
    PUNCTUATION = "punctuation"
    # phonology (audio phases; text phase only via STT suspicion)
    PRONUNCIATION_SUSPECTED = "pronunciation_suspected"  # inferred from STT confusion, low confidence
    PROSODY = "prosody"                  # stress, intonation
    # comprehension
    MISUNDERSTANDING = "misunderstanding"  # response shows the tutor's utterance wasn't understood


SUBCATEGORIES: dict[ErrorCategory, tuple[ErrorSubcategory, ...]] = {
    ErrorCategory.MORPHOSYNTAX: (
        ErrorSubcategory.AGREEMENT,
        ErrorSubcategory.TENSE_ASPECT,
        ErrorSubcategory.MOOD,
        ErrorSubcategory.CASE,
        ErrorSubcategory.WORD_ORDER,
        ErrorSubcategory.DETERMINER,
        ErrorSubcategory.PREPOSITION,
        ErrorSubcategory.PRONOUN,
        ErrorSubcategory.NEGATION,
        ErrorSubcategory.CONJUGATION,
    ),
    ErrorCategory.LEXIS: (
        ErrorSubcategory.LEXICAL_CHOICE,
        ErrorSubcategory.FALSE_FRIEND,
        ErrorSubcategory.COLLOCATION,
        ErrorSubcategory.WORD_FORMATION,
        ErrorSubcategory.CALQUE,
        ErrorSubcategory.MISSING_WORD,
    ),
    ErrorCategory.PRAGMATICS: (
        ErrorSubcategory.REGISTER,
        ErrorSubcategory.IDIOMATICITY,
        ErrorSubcategory.DISCOURSE,
    ),
    ErrorCategory.ORTHOGRAPHY: (
        ErrorSubcategory.SPELLING,
        ErrorSubcategory.DIACRITICS,
        ErrorSubcategory.PUNCTUATION,
    ),
    ErrorCategory.PHONOLOGY: (
        ErrorSubcategory.PRONUNCIATION_SUSPECTED,
        ErrorSubcategory.PROSODY,
    ),
    ErrorCategory.COMPREHENSION: (
        ErrorSubcategory.MISUNDERSTANDING,
    ),
}

CATEGORY_OF: dict[ErrorSubcategory, ErrorCategory] = {
    sub: cat for cat, subs in SUBCATEGORIES.items() for sub in subs
}


class Severity(IntEnum):
    """Anchored 1-4 ordinal. Impact of THIS occurrence on communication.

    The anchors below are the single source of truth for both human review and
    the LLM detector (they are embedded verbatim in the annotation tool schema),
    so all raters share one scale. Recurrence/fossilization is deliberately NOT
    encoded here — that is pattern-level state (error_patterns.status), because
    it is a property of repetition, not of a single event.
    """

    SLIP = 1        # Performance slip: learner almost certainly knows the rule
                    # (produces it correctly elsewhere); typo-like; self-corrected.
    MINOR = 2       # Competence error in form; meaning fully recoverable with no
                    # effort. The bread-and-butter learner error.
    DISRUPTIVE = 3  # Meaning distorted or effortful to recover; the utterance
                    # says something other than intended ("estoy embarazada" for
                    # "I'm embarrassed").
    BREAKDOWN = 4   # Communication fails: utterance uninterpretable, or so
                    # misleading the conversation derails without repair.


SEVERITY_ANCHORS: dict[Severity, str] = {
    Severity.SLIP: (
        "1 SLIP — performance slip; the learner demonstrably knows the rule "
        "(correct elsewhere in the conversation), typo-like, or self-corrected."
    ),
    Severity.MINOR: (
        "2 MINOR — competence error in form; meaning fully recoverable with no "
        "listener effort."
    ),
    Severity.DISRUPTIVE: (
        "3 DISRUPTIVE — meaning distorted or effortful to recover; the utterance "
        "conveys something other than what was intended."
    ),
    Severity.BREAKDOWN: (
        "4 BREAKDOWN — communication fails; uninterpretable or derails the "
        "conversation without explicit repair."
    ),
}


def render_for_prompt() -> str:
    """Compact taxonomy text for embedding in tool descriptions / prompts."""
    lines = ["Error categories and subcategories:"]
    for cat, subs in SUBCATEGORIES.items():
        lines.append(f"- {cat.value}: " + ", ".join(s.value for s in subs))
    lines.append("Severity anchors:")
    lines.extend(f"- {anchor}" for anchor in SEVERITY_ANCHORS.values())
    return "\n".join(lines)
